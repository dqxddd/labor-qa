# 两种风格共用的硬规则。改这里等于两种风格一起改，动之前想清楚。
STYLE_COMMON = """

不管用什么风格，下面几条都必须守住：
1. 只依据资料片段里的内容作答，不要用资料以外的知识
2. 每个结论后面标上来源编号，比如 [1]、[2]
3. 资料里找不到依据时，直接说"资料库里没有相关内容"，不要猜
4. 涉及时效、金额、比例的数字要照抄资料原文，别自己算
   （系统业务工具算出来的日期是唯一例外 —— 那是按法规算好的，可以直接用）"""


STYLES = {
    "plain": {
        "name": "劳动者通俗版",
        "hint": "说人话、先给结论、配日常例子",
        "prompt": """你是劳动权益咨询助手，对面是一个遇到了劳动纠纷、但没学过法律的普通劳动者。

说话方式：
- 用日常说法：老板、公司、你签的那份合同、走人，别堆法言法语；非引原文不可时用括号解释一下
- 第一句先直接给结论，比如"最长 6 个月"，别绕圈子
- 然后 ①②③ 分点说清楚，每点尽量配一个具体情境，比如"你试用期被辞，能拿半个月工资"
- 结尾用一句大白话提醒他这件事要注意什么"""
        + STYLE_COMMON,
    },
    "strict": {
        "name": "严谨条款版",
        "hint": "照引条文原文、标条款号、不作发挥",
        "prompt": """你是劳动法规条文检索助手，输出对象是需要核对条文原文的法务、HR 一类读者。

说话方式：
- 用规范表述：用人单位、劳动者、劳动合同期限，不用口语化称呼
- 用「一、（一）（二）」的层级组织；每个结论先写条款出处（法规名称 + 条款号），再照录原文表述
- 不举例、不做解释性发挥、不写口语化的提醒
- 结尾按顺序列出本条回答引用到的资料文件名"""
        + STYLE_COMMON,
    },
}

DEFAULT_STYLE = "plain"


def resolve_style(style):
    """容错：前端没传、或者传了不认识的值，就退回默认风格，别让接口报错"""
    return style if style in STYLES else DEFAULT_STYLE


def style_name(style):
    """风格的中文名。前端拿它打标签，结果里也带着，方便核对这轮用的哪种"""
    return STYLES[resolve_style(style)]["name"]


def style_options():
    """/health 报给前端的风格清单 —— 前端不写死这两个名字，加风格只动这里"""
    return [{"key": k, "name": v["name"], "hint": v["hint"]} for k, v in STYLES.items()]


def system_prompt(style=DEFAULT_STYLE):
    """按风格取系统提示词"""
    return STYLES[resolve_style(style)]["prompt"]


def build_context(chunks):
    """chunks 是 [(编号, 文件名, 内容)]，拼成给模型看的资料块"""
    parts = []
    for index, file_name, content in chunks:
        parts.append("[%d] 来源：%s\n%s" % (index, file_name, content))
    return "\n\n".join(parts)


# 开了多轮追问时，历史问答会插在系统提示和本轮资料之间。
# 这里明确告诉模型历史只用来认指代，别拿历史里的结论当依据。
HISTORY_HINT = ("上面是这个会话里前面的问答，只用来理解「那」「这个」「它」指的是什么事。"
                "回答依据始终是下面给的资料片段，不要沿用历史里的结论，"
                "也不要因为历史里说过就重复引用。")


def build_user_prompt(question, chunks, with_history=False):
    """with_history=True 时在前面加一句历史说明（模型看到的历史消息不止一条）"""
    note = (HISTORY_HINT + "\n\n") if with_history else ""
    return "%s资料片段：\n%s\n\n用户问题：%s" % (note, build_context(chunks), question)


# ==================== 业务工具（9.22 傍晚加） ====================

def tool_time_hint(today, topic_key=None, topic_name=None):
    """调工具前告诉模型今天是几号，顺带把已经判定好的类别也说一声。

    模型自己不知道当天日期，遇到"去年 3 月""上个月"这种相对说法会换算错，
    或者干脆反问用户"今天是几号"（实测 DeepSeek-V3.1 就是这样）。

    为什么还要报类别：规则层（tools.match）早就判出是哪一类了，不告诉它的话
    模型会自己猜 —— 实测"公司拖欠我工资，我 2026 年 1 月 1 日离职的"这句
    被填成了 arbitration。两类的截止日算法一样，看不出差别，但引用的条款不同：
    追索报酬要走第二十七条第四款的特殊规则，填错就把这条规则丢了。
    """
    text = ("（今天是 %s。如果用户说的是「去年 3 月」这类相对时间，"
            "请先换算成具体日期再调用工具。" % today)
    if topic_key:
        text += "这个问题属于「%s」，topic 请填 %s。" % (topic_name, topic_key)
    return text + "）"


